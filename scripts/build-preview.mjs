import { readFile, writeFile } from 'node:fs/promises';
const site = {};
for (const [file,type] of [['index.html','text/html; charset=utf-8'],['app.js','text/javascript; charset=utf-8'],['styles.css','text/css; charset=utf-8']]) {
  site[`/${file}`] = {content:await readFile(new URL(`../${file}`,import.meta.url),'utf8'),type};
}
await writeFile(new URL('../assistant/preview-assets.js',import.meta.url),`// Generated by scripts/build-preview.mjs.\nexport const SITE = ${JSON.stringify(site)};\n`);
